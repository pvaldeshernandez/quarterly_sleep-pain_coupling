def main(seed=42):
    """
    Run the full synthetic data generation pipeline.

    Steps:
    1. Generate demographics (age, sex, race).
    2. For each person:
       a. Draw number of quarterly timepoints.
       b. Draw random effects u_sp and u_ps.
       c. Generate contrast factor K and iterate VARX(1) forward.
       d. Apply within-person centering.
    3. For the fMRI subsample (first N_FMRI participants):
       a. Generate ROI BOLD values with embedded correlations.
       b. Generate VBM gray matter volumes.
    4. Save all outputs and ground truth parameters.

    Parameters
    ----------
    seed : int
        Random seed for full reproducibility.
    """
    print(f"Generating synthetic data with seed={seed} ...")
    rng = np.random.default_rng(seed)

    # --- Step 1: Demographics ----------------------------------------------
    n = DEMO["N"]
    demo_df, age_z, sex_c = generate_demographics(rng, n, DEMO)
    print(f"  Demographics: N={n}, "
          f"age={demo_df['age'].mean():.1f} +/- {demo_df['age'].std():.1f}, "
          f"{demo_df['sex'].mean()*100:.1f}% female")

    # --- Step 2: Time series -----------------------------------------------
    n_timepoints = generate_timepoints(rng, n)
    total_transitions = (n_timepoints - 1).sum()
    print(f"  Timepoints: median={int(np.median(n_timepoints))}, "
          f"range=[{n_timepoints.min()}, {n_timepoints.max()}], "
          f"total transitions={total_transitions}")

    # Draw random effects for all participants at once.
    # u_sp_i ~ N(0, tau_sp^2): person-specific deviation in sleep->pain coupling
    # u_ps_i ~ N(0, tau_ps^2): person-specific deviation in pain->sleep coupling
    # These are drawn independently; the model does not assume correlation
    # between the two random effects (they are on different equations).
    u_sp = rng.normal(0, PARAMS["tau_sp"], size=n)
    u_ps = rng.normal(0, PARAMS["tau_ps"], size=n)

    # Iterate over participants and simulate each person's time series
    all_rows = []
    for i in range(n):
        nt = n_timepoints[i]

        # Simulate raw time series
        pain_raw, sleep_raw, contrast_raw = simulate_varx1(
            rng, nt, PARAMS, age_z[i], sex_c[i], u_sp[i], u_ps[i]
        )

        # Apply within-person centering.
        # After this step, each person's mean pain, sleep, and contrast are 0.
        # The estimation model works entirely with these centered values.
        pain_ctr    = within_person_center(pain_raw)
        sleep_ctr   = within_person_center(sleep_raw)
        contrast_ctr = within_person_center(contrast_raw)

        # Store both raw and centered values.
        # The CSV output contains the raw values; the analysis pipeline
        # will re-center them itself.  We save the raw values so that
        # the synthetic data has the same structure as the real data file.
        sid = demo_df.loc[i, "subject_id"]
        for t in range(nt):
            all_rows.append({
                "subject_id":      sid,
                "quarter":         t + 1,  # 1-indexed (quarter 1, 2, ..., 10)
                "pain_severity":   round(float(pain_raw[t]), 4),
                "contrast_factor": round(float(contrast_raw[t]), 4),
                "sleep_quality":   round(float(sleep_raw[t]), 4),
            })

    quarterly_df = pd.DataFrame(all_rows)
    print(f"  Quarterly data: {len(quarterly_df)} rows "
          f"({n} subjects x variable timepoints)")

    # --- Step 3: fMRI subsample --------------------------------------------
    # The fMRI subsample is the first N_FMRI participants.
    # (In the real study, fMRI availability was essentially random with
    # respect to the coupling parameters, so arbitrary selection is fine.)
    fmri_indices = np.arange(N_FMRI)

    roi_df = generate_fmri_rois(rng, N_FMRI, u_sp, fmri_indices)
    vbm_df = generate_vbm_volumes(rng, N_FMRI, u_ps, fmri_indices)
    print(f"  fMRI subsample: N={N_FMRI}, "
          f"{len(FMRI_SP_GAMMAS)} BOLD ROIs, "
          f"{len(VBM_PS_GAMMAS)} VBM ROIs")

    # --- Step 4: Save outputs ----------------------------------------------
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    # 4a. Quarterly longitudinal data
    quarterly_path = os.path.join(OUTPUT_DIR, "quarterly_data_long.csv")
    quarterly_df.to_csv(quarterly_path, index=False)
    print(f"  Saved: {quarterly_path}")

    # 4b. Participant demographics
    # Only save the raw demographics (subject_id, age, sex, race).
    # The analysis pipeline computes age_z and sex_c from these.
    demo_path = os.path.join(OUTPUT_DIR, "participants_wideformat.csv")
    demo_df.to_csv(demo_path, index=False)
    print(f"  Saved: {demo_path}")

    # 4c. fMRI ROI values (BOLD)
    roi_path = os.path.join(OUTPUT_DIR, "roi_values.csv")
    roi_df.to_csv(roi_path, index=False)
    print(f"  Saved: {roi_path}")

    # 4d. VBM gray matter volumes
    vbm_path = os.path.join(OUTPUT_DIR, "vbm_volumes.csv")
    vbm_df.to_csv(vbm_path, index=False)
    print(f"  Saved: {vbm_path}")

    # 4e. Ground truth parameters (everything needed to verify recovery)
    ground_truth = {
        "description": (
            "Ground truth parameters used to generate synthetic data. "
            "These are the population-level estimates from the real analysis "
            "(Tables 3-5 of the manuscript) and can be compared against "
            "estimates obtained by fitting the model to this synthetic data."
        ),
        "seed": seed,
        "varx1_fixed_effects": {
            k: v for k, v in PARAMS.items()
            if k not in ("tau_sp", "tau_ps", "sigma_p", "sigma_s", "rho")
        },
        "random_effects": {
            "tau_sp": PARAMS["tau_sp"],
            "tau_ps": PARAMS["tau_ps"],
        },
        "innovations": {
            "sigma_p": PARAMS["sigma_p"],
            "sigma_s": PARAMS["sigma_s"],
            "rho":     PARAMS["rho"],
        },
        "demographics": {
            "N": n,
            "age_mean": round(float(demo_df["age"].mean()), 2),
            "age_sd":   round(float(demo_df["age"].std()), 2),
            "pct_female": round(float(demo_df["sex"].mean()), 3),
            "race_counts": demo_df["race"].value_counts().to_dict(),
        },
        "timepoints": {
            "median":            int(np.median(n_timepoints)),
            "min":               int(n_timepoints.min()),
            "max":               int(n_timepoints.max()),
            "total_transitions": int(total_transitions),
        },
        "fmri_subsample": {
            "N_fmri": N_FMRI,
            "sp_moderation_gammas": FMRI_SP_GAMMAS,
            "sp_embedded_correlations": FMRI_SP_CORR_WITH_U_SP,
            "vbm_ps_moderation_gammas": VBM_PS_GAMMAS,
        },
    }

    truth_path = os.path.join(OUTPUT_DIR, "ground_truth.json")
    with open(truth_path, "w") as f:
        json.dump(ground_truth, f, indent=2)
    print(f"  Saved: {truth_path}")

    # --- Summary statistics for verification --------------------------------
    print("\n  === Verification summary ===")
    print(f"  Pain severity: mean={quarterly_df['pain_severity'].mean():.3f}, "
          f"SD={quarterly_df['pain_severity'].std():.3f}")
    print(f"  Sleep quality:  mean={quarterly_df['sleep_quality'].mean():.3f}, "
          f"SD={quarterly_df['sleep_quality'].std():.3f}")
    print(f"  Contrast:       mean={quarterly_df['contrast_factor'].mean():.3f}, "
          f"SD={quarterly_df['contrast_factor'].std():.3f}")
    print(f"  u_sp SD={u_sp.std():.3f} (target: {PARAMS['tau_sp']:.3f})")
    print(f"  u_ps SD={u_ps.std():.3f} (target: {PARAMS['tau_ps']:.3f})")
    print("\n  Done.")


