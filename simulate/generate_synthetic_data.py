#!/usr/bin/env python3
"""
generate_synthetic_data.py
==========================
Parametric synthetic data generator for the quarterly sleep-pain coupling
analysis pipeline.

This script generates simulated data that mirrors the structure of the real
UPLOAD2 knee-pain cohort so the full Python analysis pipeline can run
end-to-end without access to restricted participant data.

The ground-truth parameters are taken directly from the manuscript
(Tables 3-5) and reproduce the key statistical signatures of the real data:
bidirectional coupling, contrast-factor moderation, left-NAcc moderation of
the sleep-to-pain path, and null age/sex moderation.

Model
-----
The data-generating process is a Vector Autoregressive model with exogenous
input, order 1 — a VARX(1).  At each quarterly transition, two within-person
centered variables (pain severity and sleep quality) are predicted from their
own lagged values and from a time-varying exogenous contrast factor (kappa).

Let  p_w(t) = within-person centered pain at quarter t
     s_w(t) = within-person centered sleep at quarter t
     K(t)   = within-person centered contrast factor at quarter t

The two equations are:

  Pain equation:
    p_w(t) = mu_p
           + phi_p      * p_w(t-1)          [pain autoregression]
           + lambda_sp_i * s_w(t-1)          [sleep -> pain coupling]
           + delta_p     * K(t-1)            [contrast direct effect on pain]
           + omega_sp    * s_w(t-1) * K(t-1) [sleep x contrast interaction]
           + epsilon_p(t)

  Sleep equation:
    s_w(t) = mu_s
           + lambda_ps_i * p_w(t-1)          [pain -> sleep coupling]
           + phi_s       * s_w(t-1)          [sleep autoregression]
           + delta_s     * K(t-1)            [contrast direct effect on sleep]
           + omega_ps    * p_w(t-1) * K(t-1) [pain x contrast interaction]
           + epsilon_s(t)

The coupling coefficients are person-specific:

  lambda_sp_i = lambda_sp
              + gamma_sp_age * Age_z_i
              + gamma_sp_sex * Sex_c_i
              + u_sp_i

  lambda_ps_i = lambda_ps
              + gamma_ps_age * Age_z_i
              + gamma_ps_sex * Sex_c_i
              + u_ps_i

where u_sp_i ~ N(0, tau_sp^2) and u_ps_i ~ N(0, tau_ps^2) are random effects.

Correlated Innovations (the Cholesky Trick)
--------------------------------------------
In a bivariate system the innovation terms (residuals) of the two equations
may be contemporaneously correlated.  If a person has an unexpectedly bad
pain day, they may also have unexpectedly poor sleep that same quarter.
We model this with a 2x2 covariance matrix:

  Sigma = | sigma_p^2                   rho*sigma_p*sigma_s |
          | rho*sigma_p*sigma_s         sigma_s^2           |

To draw correlated innovations efficiently, we use the Cholesky
decomposition.  Instead of sampling from a 2-d multivariate normal (which
requires constructing and inverting the full covariance matrix each time),
we draw two independent standard normals z1, z2 and transform them:

  epsilon_p = sigma_p * z1
  epsilon_s = rho * sigma_s * z1  +  sigma_s * sqrt(1 - rho^2) * z2

This is algebraically identical to sampling from MVN(0, Sigma) but is
~100x faster in a loop.  The same trick is used in the PyMC estimation
model.

Within-Person Centering
-----------------------
The real analysis pipeline works with within-person centered data: each
person's time series is demeaned so that between-person differences in
mean pain level or mean sleep quality are removed.  This eliminates the
need for random intercepts and between-person covariates, isolating the
*dynamics* (how changes in sleep predict changes in pain, and vice versa).

In this generator, we simulate the *raw* (uncentered) time series first,
then apply within-person centering post-hoc, exactly as done with the
real data.  The raw series are generated by initializing each person's
first observation from a reasonable marginal distribution and then
iterating the VARX(1) forward.  After centering, the first usable
"transition" for each person starts at t=1 (lag from t=0 to t=1).

References
----------
[1] Valdes-Hernandez PA et al. (2026). Quarterly Sleep-Pain Coupling in
    Knee Pain. [manuscript in preparation]
[2] Hamilton JD. Time Series Analysis. Princeton University Press, 1994.
    — Chapter 11: Vector autoregressive models.
[3] Bolger N, Laurenceau JP. Intensive Longitudinal Methods. Guilford, 2013.
    — Within-person centering for diary/EMA designs.

Usage
-----
  python simulate/generate_synthetic_data.py [--seed 42]

Outputs (relative to repository root):
  data/synthetic/quarterly_data_long.csv
  data/synthetic/participants_wideformat.csv
  data/synthetic/roi_values.csv
  data/synthetic/vbm_volumes.csv
  data/synthetic/ground_truth.json
"""

