def generate_demographics(rng, n, demo):
    """
    Generate a demographics table for n simulated participants.

    Parameters
    ----------
    rng : numpy.random.Generator
        Random number generator (for reproducibility).
    n : int
        Number of participants.
    demo : dict
        Demographic distribution parameters.

    Returns
    -------
    pd.DataFrame
        Columns: subject_id, age, sex, race, age_z, sex_c
        - age: continuous, truncated to [age_min, age_max]
        - sex: 0 = male, 1 = female
        - race: categorical string
        - age_z: z-scored age (mean 0, SD 1)
        - sex_c: centered sex (sex - proportion female)
    """
    # --- Age ---
    # Draw from a normal distribution and clip to the observed range.
    # The truncation is mild (the range is ~6 SDs wide) so the resulting
    # distribution is nearly Gaussian.
    ages = rng.normal(demo["age_mean"], demo["age_sd"], size=n)
    ages = np.clip(ages, demo["age_min"], demo["age_max"])

    # --- Sex ---
    # Bernoulli draw: 1 = female with probability pct_female.
    sex = rng.binomial(1, demo["pct_female"], size=n)

    # --- Race ---
    # Multinomial draw from the four categories.
    race_categories = list(demo["race_probs"].keys())
    race_probabilities = list(demo["race_probs"].values())
    race = rng.choice(race_categories, size=n, p=race_probabilities)

    # --- Centering ---
    # Age is z-scored (subtract sample mean, divide by sample SD) so that
    # the moderation coefficients are interpretable as "effect per SD of age."
    age_z = (ages - ages.mean()) / ages.std()
    # Sex is mean-centered so that the main coupling effects (lambda_sp,
    # lambda_ps) are evaluated at the sample-average sex composition,
    # not at sex=0 (i.e., not "for males only").
    sex_c = sex - sex.mean()

    df = pd.DataFrame({
        "subject_id": [f"sub-{i+1:03d}" for i in range(n)],
        "age":        np.round(ages, 1),
        "sex":        sex,
        "race":       race,
    })
    # We return the centered versions separately (used in simulation but
    # not saved to the demographics file — the analysis pipeline recomputes
    # them from raw age and sex).
    return df, age_z, sex_c


def generate_timepoints(rng, n):
    """
    Draw number of quarterly timepoints for each participant.

    Most participants completed all 10 visits (40 months of follow-up).
    The distribution is left-skewed, with a few people having as few as 2.

    Parameters
    ----------
    rng : numpy.random.Generator
    n : int

    Returns
    -------
    np.ndarray of int, shape (n,)
        Number of timepoints per person (between 2 and 10).
    """
    n_timepoints = rng.choice(TIMEPOINT_VALUES, size=n, p=TIMEPOINT_PROBS)
    return n_timepoints


def simulate_varx1(rng, n_t, params, age_z_i, sex_c_i, u_sp_i, u_ps_i):
    """
    Simulate one person's quarterly time series from the VARX(1) model.

    This function iterates the bivariate VAR forward in time, generating
    raw (uncentered) pain and sleep values plus a contrast factor series.

    Parameters
    ----------
    rng : numpy.random.Generator
    n_t : int
        Number of timepoints for this person (including t=0 initial value).
    params : dict
        Population-level parameters.
    age_z_i : float
        This person's z-scored age.
    sex_c_i : float
        This person's centered sex.
    u_sp_i : float
        This person's random effect on the sleep->pain coupling path.
    u_ps_i : float
        This person's random effect on the pain->sleep coupling path.

    Returns
    -------
    pain : np.ndarray, shape (n_t,)
        Simulated pain severity (raw, before within-person centering).
    sleep : np.ndarray, shape (n_t,)
        Simulated sleep quality (raw, before within-person centering).
    contrast : np.ndarray, shape (n_t,)
        Contrast factor values (time-varying exogenous predictor).
    """
    # Unpack parameters for readability
    mu_p      = params["mu_p"]
    phi_p     = params["phi_p"]
    lambda_sp = params["lambda_sp"]
    delta_p   = params["delta_p"]
    omega_sp  = params["omega_sp"]
    mu_s      = params["mu_s"]
    lambda_ps = params["lambda_ps"]
    phi_s     = params["phi_s"]
    delta_s   = params["delta_s"]
    omega_ps  = params["omega_ps"]
    sigma_p   = params["sigma_p"]
    sigma_s   = params["sigma_s"]
    rho       = params["rho"]
    g_sp_age  = params["gamma_sp_age"]
    g_sp_sex  = params["gamma_sp_sex"]
    g_ps_age  = params["gamma_ps_age"]
    g_ps_sex  = params["gamma_ps_sex"]

    # --- Person-specific coupling coefficients ---
    # These are constant across time for a given person (the random effects
    # and demographics don't change across quarters).  The omega*K interaction
    # term is added inside the loop because K varies over time.
    lambda_sp_base = lambda_sp + g_sp_age * age_z_i + g_sp_sex * sex_c_i + u_sp_i
    lambda_ps_base = lambda_ps + g_ps_age * age_z_i + g_ps_sex * sex_c_i + u_ps_i

    # --- Contrast factor ---
    # The contrast factor kappa captures localized vs. widespread pain.
    # It is derived from a 2-factor model of quarterly pain items.
    # In the real data it is approximately standard normal within-person.
    # We generate it as iid N(0, 1) for simplicity; within-person centering
    # later will ensure mean 0 per person.
    contrast = rng.normal(0, 1, size=n_t)

    # --- Initialize time series ---
    pain  = np.zeros(n_t)
    sleep = np.zeros(n_t)

    # Initial values (t=0): draw from a marginal distribution.
    # Since the within-person-centered variables have mean ~0 and SD ~0.5-0.7,
    # we initialize from N(0, sigma) for each.  These initial values will be
    # absorbed by the within-person centering step; they don't affect the
    # estimated coupling parameters.
    pain[0]  = rng.normal(0, sigma_p)
    sleep[0] = rng.normal(0, sigma_s)

    # --- Forward iteration ---
    # For each subsequent timepoint, compute the predicted value from the
    # lagged predictors plus a correlated innovation.
    for t in range(1, n_t):
        # Lagged values
        p_lag = pain[t - 1]
        s_lag = sleep[t - 1]
        k_lag = contrast[t - 1]

        # Time-varying coupling (includes contrast interaction)
        # The omega terms capture how the coupling changes as a function of
        # pain localization: when kappa is high (more widespread pain),
        # the coupling may strengthen or weaken.
        lambda_sp_t = lambda_sp_base + omega_sp * k_lag
        lambda_ps_t = lambda_ps_base + omega_ps * k_lag

        # Deterministic (predicted) component of each equation
        pain_pred  = mu_p + phi_p * p_lag + lambda_sp_t * s_lag + delta_p * k_lag
        sleep_pred = mu_s + lambda_ps_t * p_lag + phi_s * s_lag + delta_s * k_lag

        # --- Correlated innovations via Cholesky decomposition ---
        #
        # We need:
        #   [epsilon_p]   ~  MVN( [0], [sigma_p^2              rho*sigma_p*sigma_s] )
        #   [epsilon_s]        ( [0], [rho*sigma_p*sigma_s     sigma_s^2          ] )
        #
        # The Cholesky factor L of the 2x2 covariance matrix is:
        #   L = [sigma_p,         0                        ]
        #       [rho*sigma_s,     sigma_s*sqrt(1-rho^2)    ]
        #
        # So: [epsilon_p, epsilon_s]^T = L @ [z1, z2]^T
        #   where z1, z2 ~ N(0, 1) independently.
        #
        # Expanding:
        #   epsilon_p = sigma_p * z1
        #   epsilon_s = rho * sigma_s * z1  +  sigma_s * sqrt(1 - rho^2) * z2
        #
        # This gives the correct marginal variances and cross-covariance,
        # and avoids the overhead of constructing a 2x2 matrix each iteration.

        z1 = rng.standard_normal()
        z2 = rng.standard_normal()

        eps_p = sigma_p * z1
        eps_s = rho * sigma_s * z1 + sigma_s * np.sqrt(1 - rho**2) * z2

        pain[t]  = pain_pred + eps_p
        sleep[t] = sleep_pred + eps_s

    return pain, sleep, contrast


def within_person_center(values):
    """
    Subtract the person's own mean from a time series.

    Within-person centering removes stable between-person differences
    (e.g., one person always rates pain higher than another) and isolates
    the *fluctuations* around each person's own average.  This is the
    standard preprocessing step in intensive longitudinal designs
    (Bolger & Laurenceau, 2013).

    After centering, the mean of each person's series is exactly 0,
    so random intercepts are unnecessary in the estimation model.

    Parameters
    ----------
    values : np.ndarray
        Raw time series for one person.

    Returns
    -------
    np.ndarray
        Centered time series (same length, mean = 0).
    """
    return values - values.mean()


def generate_fmri_rois(rng, n_fmri, u_sp, fmri_indices):
    """
    Generate z-scored fMRI BOLD ROI values for the fMRI subsample.

    For most ROIs, the values are simply drawn from N(0,1) — they have no
    true relationship with the coupling random effects, so the estimated
    moderation gamma should be null.

    For the two ROIs with significant moderation (left NAcc and right
    dACC/MCC), we embed a correlation between the ROI z-score and the
    person's random effect u_sp_i.  This ensures that when the analysis
    model estimates gamma_sp for these ROIs, it will recover a nonzero
    value, reproducing the key finding.

    The embedded correlation is achieved by constructing the ROI value as
    a weighted combination of the random effect (signal) and independent
    noise.  If the target correlation is r, then:

        roi_value = r * u_sp_z + sqrt(1 - r^2) * noise

    where u_sp_z is the z-scored random effect and noise ~ N(0,1).
    This gives  corr(roi, u_sp) = r  exactly (in expectation).

    Parameters
    ----------
    rng : numpy.random.Generator
    n_fmri : int
        Number of participants in the fMRI subsample.
    u_sp : np.ndarray, shape (N_total,)
        Sleep-to-pain random effects for all participants.
    fmri_indices : np.ndarray of int, shape (n_fmri,)
        Indices into the full sample identifying fMRI participants.

    Returns
    -------
    pd.DataFrame
        Long-format: subject_id, roi_name, bold_value
    """
    # Z-score the random effects for the fMRI subsample
    u_sp_sub = u_sp[fmri_indices]
    u_sp_z = (u_sp_sub - u_sp_sub.mean()) / u_sp_sub.std()

    rows = []
    for roi_name in FMRI_SP_GAMMAS:
        # Check if this ROI has an embedded correlation
        r = FMRI_SP_CORR_WITH_U_SP.get(roi_name, 0.0)

        if r > 0:
            # Signal + noise mixture to achieve target correlation
            noise = rng.standard_normal(n_fmri)
            roi_values = r * u_sp_z + np.sqrt(1 - r**2) * noise
        else:
            # Pure noise — no relationship with random effects
            roi_values = rng.standard_normal(n_fmri)

        # Z-score the final ROI values (analysis pipeline expects z-scored)
        roi_values = (roi_values - roi_values.mean()) / roi_values.std()

        for j in range(n_fmri):
            rows.append({
                "subject_id": f"sub-{fmri_indices[j]+1:03d}",
                "roi_name":   roi_name,
                "bold_value": round(float(roi_values[j]), 6),
            })

    return pd.DataFrame(rows)


def generate_vbm_volumes(rng, n_fmri, u_ps, fmri_indices):
    """
    Generate gray matter volume values for VBM arousal ROIs.

    In the real data, none of the VBM arousal ROI volumes significantly
    moderated the pain-to-sleep coupling path individually (all p > 0.05).
    However, there was a notable sign concordance: all 5 gamma_ps estimates
    were negative (binomial p = 0.031), suggesting a weak but consistent
    directional effect.

    We generate these as independent standard normal values with a very
    slight negative correlation with u_ps to preserve the sign pattern,
    but not strong enough for any individual ROI to reach significance.

    Parameters
    ----------
    rng : numpy.random.Generator
    n_fmri : int
    u_ps : np.ndarray, shape (N_total,)
        Pain-to-sleep random effects for all participants.
    fmri_indices : np.ndarray of int

    Returns
    -------
    pd.DataFrame
        Long-format: subject_id, roi_name, gm_volume
    """
    # Z-score the pain-to-sleep random effects for the fMRI subsample
    u_ps_sub = u_ps[fmri_indices]
    u_ps_z = (u_ps_sub - u_ps_sub.mean()) / u_ps_sub.std()

    rows = []
    for roi_name, gamma in VBM_PS_GAMMAS.items():
        # Embed a very weak correlation in the direction of gamma
        # to preserve the sign concordance pattern.
        # We use r = sign(gamma) * 0.08 — weak enough to be individually
        # null but consistent across ROIs.
        r = np.sign(gamma) * 0.08

        noise = rng.standard_normal(n_fmri)
        vol_values = r * u_ps_z + np.sqrt(1 - r**2) * noise

        # Scale to a plausible GM volume range (arbitrary units, z-scored
        # in the analysis pipeline anyway)
        vol_values = (vol_values - vol_values.mean()) / vol_values.std()

        for j in range(n_fmri):
            rows.append({
                "subject_id": f"sub-{fmri_indices[j]+1:03d}",
                "roi_name":   roi_name,
                "gm_volume":  round(float(vol_values[j]), 6),
            })

    return pd.DataFrame(rows)


